-- Migration 002 : Demande client (Takt Time) + Échéance de livraison (Production à temps)
-- À exécuter dans le SQL Editor de Supabase (ou via la CLI : supabase db push).
-- Active deux KPI du Tableau de bord qui étaient en « N/A ».
-- Convention : RLS activé + 4 policies (select/insert/update/delete) to authenticated.

-- =====================================================================
-- 1) Demande client mensuelle par produit  →  KPI « Takt Time »
--    Takt = temps disponible / demande. Une ligne par produit / année / mois.
-- =====================================================================
create table if not exists public.demande_client (
  id bigint generated by default as identity primary key,
  produit_id bigint not null references public.produits(id) on delete cascade,
  annee int not null,
  mois int not null check (mois between 1 and 12),
  quantite_demandee numeric not null default 0,   -- en boîtes (même unité que la production)
  actif boolean not null default true,
  commentaire text,
  created_at timestamptz default now(),
  unique (produit_id, annee, mois)
);

alter table public.demande_client enable row level security;

create policy "demande_client sel" on public.demande_client for select to authenticated using (true);
create policy "demande_client ins" on public.demande_client for insert to authenticated with check (true);
create policy "demande_client upd" on public.demande_client for update to authenticated using (true);
create policy "demande_client del" on public.demande_client for delete to authenticated using (true);

-- =====================================================================
-- 2) Échéance de livraison sur les OF  →  KPI « Production à temps »
--    % de lots dont la fin de fabrication est <= à l'échéance visée.
-- =====================================================================
alter table public.ordres_fabrication
  add column if not exists date_echeance date;

comment on column public.ordres_fabrication.date_echeance is
  'Échéance de livraison visée (date cible). Sert au KPI « Production à temps ».';
