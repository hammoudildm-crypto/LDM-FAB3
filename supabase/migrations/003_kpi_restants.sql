-- Migration 003 : activer les 4 derniers KPI « N/A » du Tableau de bord.
-- À exécuter dans le SQL Editor de Supabase (ou via la CLI : supabase db push).
-- Convention : RLS activé + 4 policies (select/insert/update/delete) to authenticated.

-- =====================================================================
-- 1) Taux de retouche  →  unités retouchées, au même grain que les rebuts
-- =====================================================================
alter table public.trs_postes
  add column if not exists retouches numeric not null default 0;
comment on column public.trs_postes.retouches is
  'Nombre d''unités retouchées (reprises). Sert au KPI « Taux de retouche ».';

-- =====================================================================
-- 2) Taux d'utilisation capacité  →  heures d'ouverture théoriques (calendrier)
--    par équipement et par mois (capacité installée en temps).
-- =====================================================================
alter table public.equipements
  add column if not exists heures_theoriques_mois numeric;
comment on column public.equipements.heures_theoriques_mois is
  'Heures d''ouverture théoriques par mois (capacité calendaire). Sert au KPI « Taux d''utilisation capacité ».';

-- Note : le KPI « Coût de production / unité » utilise le PCSU déjà présent
-- dans le référentiel produit (produits.pcsu) — aucune colonne de coût séparée.

-- =====================================================================
-- 3) Équilibrage de ligne  →  temps de cycle par poste de travail d'une ligne
-- =====================================================================
create table if not exists public.postes_ligne (
  id bigint generated by default as identity primary key,
  equipement_id bigint not null references public.equipements(id) on delete cascade,
  ordre int not null default 1,            -- position du poste dans la ligne
  libelle text not null,                   -- nom du poste (ex. « Alimentation », « Sertissage »)
  temps_cycle_sec numeric not null default 0,  -- temps de cycle unitaire du poste (secondes)
  actif boolean not null default true,
  created_at timestamptz default now()
);

alter table public.postes_ligne enable row level security;

create policy "postes_ligne sel" on public.postes_ligne for select to authenticated using (true);
create policy "postes_ligne ins" on public.postes_ligne for insert to authenticated with check (true);
create policy "postes_ligne upd" on public.postes_ligne for update to authenticated using (true);
create policy "postes_ligne del" on public.postes_ligne for delete to authenticated using (true);
