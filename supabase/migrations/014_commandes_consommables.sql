-- Migration 014 : commandes & approvisionnement des consommables.
-- Une ligne = une commande fournisseur pour un consommable. À la réception,
-- l'application crée un mouvement d'entrée en Stock MP et met à jour le stock
-- et le statut de la commande (en_cours -> partielle -> recue).
-- À exécuter dans le SQL Editor de Supabase (ou via la CLI : supabase db push).

create table if not exists public.commandes_consommables (
  id                 bigint generated by default as identity primary key,
  consommable_id     bigint references public.consommables(id) on delete cascade,
  fournisseur        text,
  reference_commande text,                                   -- n° bon de commande
  quantite_commandee numeric not null default 0,
  quantite_recue     numeric not null default 0,
  unite              text,                                   -- unité au moment de la commande (snapshot)
  prix_unitaire      numeric not null default 0,             -- prix unitaire DA (snapshot)
  date_commande      date not null default current_date,
  date_prevue        date,                                   -- livraison prévue
  statut             text not null default 'en_cours',       -- en_cours | partielle | recue | annulee
  emplacement        text not null default 'mp',             -- destination à la réception
  commentaire        text,
  created_at         timestamptz not null default now()
);
create index if not exists idx_cmd_conso on public.commandes_consommables(consommable_id, statut);
comment on table public.commandes_consommables is 'Commandes fournisseurs des consommables : suivi des commandes en cours et de l''approvisionnement (réception -> entrée Stock MP).';

-- RLS (convention du projet : RLS activé + 4 policies to authenticated)
alter table public.commandes_consommables enable row level security;
create policy "cmd sel" on public.commandes_consommables for select to authenticated using (true);
create policy "cmd ins" on public.commandes_consommables for insert to authenticated with check (true);
create policy "cmd upd" on public.commandes_consommables for update to authenticated using (true);
create policy "cmd del" on public.commandes_consommables for delete to authenticated using (true);
