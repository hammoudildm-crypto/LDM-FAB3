-- Migration 004 : gestion des consommables (sacs polyéthylène, torchons, gants, bavettes…).
-- À exécuter dans le SQL Editor de Supabase (ou via la CLI : supabase db push).
-- Convention : chaque table a RLS activé + 4 policies (select/insert/update/delete) to authenticated.

-- =====================================================================
-- Catalogue des consommables + stock courant
-- =====================================================================
create table if not exists public.consommables (
  id bigint generated by default as identity primary key,
  nom text not null,
  categorie text,
  unite text default 'unité',
  stock_actuel numeric not null default 0,
  seuil_alerte numeric not null default 0,
  prix_unitaire numeric not null default 0,
  reference text,
  actif boolean not null default true,
  created_at timestamptz default now()
);

alter table public.consommables enable row level security;
create policy "consommables sel" on public.consommables for select to authenticated using (true);
create policy "consommables ins" on public.consommables for insert to authenticated with check (true);
create policy "consommables upd" on public.consommables for update to authenticated using (true);
create policy "consommables del" on public.consommables for delete to authenticated using (true);

-- =====================================================================
-- Mouvements de stock (entrées / sorties / ajustements)
-- =====================================================================
create table if not exists public.mouvements_consommables (
  id bigint generated by default as identity primary key,
  consommable_id bigint references public.consommables(id) on delete cascade,
  type text not null check (type in ('entree','sortie','ajustement')),
  quantite numeric not null,
  date_mvt date not null default current_date,
  atelier text,
  motif text,
  created_at timestamptz default now()
);
create index if not exists idx_mvt_conso on public.mouvements_consommables(consommable_id, date_mvt);

alter table public.mouvements_consommables enable row level security;
create policy "mvt conso sel" on public.mouvements_consommables for select to authenticated using (true);
create policy "mvt conso ins" on public.mouvements_consommables for insert to authenticated with check (true);
create policy "mvt conso upd" on public.mouvements_consommables for update to authenticated using (true);
create policy "mvt conso del" on public.mouvements_consommables for delete to authenticated using (true);
